export const QUESTIONS = new Map(SECTIONS.flatMap((s) => s.questions.map((q) => [q.id, q] as const)));
export const TOTAL = QUESTIONS.size;
export const MAX_TEXT = 2000;

// Returns the value to store, "" to clear the answer, or null if the input is invalid.
export function validateAnswer(questionId: unknown, value: unknown): string | null {
  if (typeof questionId !== "string" || typeof value !== "string") return null;
  const q = QUESTIONS.get(questionId);
  if (!q) return null;
  if (q.type === "choice") return value === "" || q.options.includes(value) ? value : null;
  const v = value.trim();
  return v.length <= MAX_TEXT ? v : null;
}
